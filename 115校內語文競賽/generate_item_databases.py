BASE_DIR = os.path.abspath("四年丙班_各項目培訓資料庫")

def save_md_and_docx(folder_name, teacher_md, teacher_builder, student_md, student_builder):
    item_dir = os.path.join(BASE_DIR, folder_name)
    os.makedirs(item_dir, exist_ok=True)
    
    t_md_path = os.path.join(item_dir, "老師_指導指引與每日進度表(含評量標準).md")
    with open(t_md_path, "w", encoding="utf-8") as f:
        f.write(teacher_md)
        
    t_doc = create_doc()
    teacher_builder(t_doc)
    t_docx_path = os.path.join(item_dir, "老師_指導指引與每日進度表(含評量標準).docx")
    t_doc.save(t_docx_path)
    
    s_md_path = os.path.join(item_dir, "學生_在校教學練習每日學習單與自評表.md")
    with open(s_md_path, "w", encoding="utf-8") as f:
        f.write(student_md)
        
    s_doc = create_doc()
    student_builder(s_doc)
    s_docx_path = os.path.join(item_dir, "學生_在校教學練習每日學習單與自評表.docx")
    s_doc.save(s_docx_path)
    
    print(f"[{folder_name}] Teacher & Student MD and DOCX generated successfully.")

